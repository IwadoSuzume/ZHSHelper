"""Project files the app needs at run time: the web UI and meta.json.

From source they are read straight from the project tree. In the packaged
build they come out of _bundle (generated by build_release.py and compiled
into the exe), so none of them ships as a readable file next to the exe.
"""
import base64
import io
import os
import sys
import zipfile

_PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# everything the bundle holds, as paths relative to the project root
FILES = (
    "gui/web/index.html",
    "gui/web/style.css",
    "gui/web/app.js",
    "gui/web/assets/logo.png",
    "meta.json",
)

_archive = None
if getattr(sys, "frozen", False):
    from _bundle import ARCHIVE

    _archive = zipfile.ZipFile(io.BytesIO(base64.b64decode(ARCHIVE)))


def read(name):
    if _archive is not None:
        return _archive.read(name)
    with open(os.path.join(_PROJECT, name), "rb") as f:
        return f.read()


def read_text(name):
    return read(name).decode("utf-8")


def ui_html():
    """The whole UI as one HTML document: stylesheet, script and logo inlined,
    so the window can be loaded from a string and nothing has to be served
    from disk."""
    html = read_text("gui/web/index.html")
    logo = "data:image/png;base64," + base64.b64encode(read("gui/web/assets/logo.png")).decode("ascii")
    # "</" inside an inline <script>/<style> would end the element early
    css = read_text("gui/web/style.css").replace("</", "<\\/")
    js = read_text("gui/web/app.js").replace("</", "<\\/")
    for old, new in (
        ('<link rel="stylesheet" href="style.css">', "<style>\n%s\n</style>" % css),
        ('<script src="app.js"></script>', "<script>\n%s\n</script>" % js),
        ('src="assets/logo.png"', 'src="%s"' % logo),
    ):
        if old not in html:
            raise RuntimeError("index.html no longer contains %r" % old)
        html = html.replace(old, new)
    return html
